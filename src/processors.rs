use std::ops::Range;

pub fn get_processor(_version: u16, name: &[u8]) -> Option<&'static Processor> {
    // TODO get and process multiples versions of the processor
    PROCESSORS
        .iter()
        .find(|p| p.alt_names().iter().any(|n| n.as_bytes() == name))
}

#[derive(Clone, PartialEq, Eq, Hash)]
pub struct Processor {
    name: &'static str,
    alt_names: &'static [&'static str],
    id: usize,
    register_names: &'static [&'static str],
    segment_registers: Range<usize>,
    segment_register_code: usize,
    segment_register_data: usize,
}

impl Processor {
    pub const fn name(&self) -> &str {
        self.name
    }

    pub const fn alt_names(&self) -> &[&str] {
        self.alt_names
    }

    pub const fn id(&self) -> usize {
        self.id
    }

    pub const fn register_names(&self) -> &[&str] {
        self.register_names
    }

    pub fn segment_register_names(&self) -> &[&str] {
        &self.register_names[self.segment_registers.clone()]
    }

    pub const fn segment_register_code_name(&self) -> &str {
        self.register_names[self.segment_register_code]
    }

    pub const fn segment_register_data_name(&self) -> &str {
        self.register_names[self.segment_register_data]
    }
}

